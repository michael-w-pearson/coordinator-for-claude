// Writes types/index.d.ts, the mod's state contract, from the data types in src/types.ts.
// The engine wants the contract to be one file with no imports, so it is generated instead of copied by hand.
// Run: node scripts/gen-contract.mjs          (rewrite)
//      node scripts/gen-contract.mjs --check  (fail when the file is out of date)
import { readFileSync, writeFileSync } from 'node:fs'

const source = readFileSync(new URL('../src/types.ts', import.meta.url), 'utf8')
const cut = source.indexOf('// ---- Host and sources')
if (cut < 0) throw new Error('marker "// ---- Host and sources" not found in src/types.ts')
const shared = source
  .slice(0, cut)
  .split('\n')
  .filter(line => !line.startsWith('export const ') && !line.startsWith('// Shared types') && !line.startsWith('// Erasable'))
  .join('\n')
  .replace(/\n{3,}/g, '\n\n')
  .trim()

const text = `// Generated by scripts/gen-contract.mjs from src/types.ts. Do not edit.
// The values this mod keeps in \`$.state\`, declared so \`claude plugin validate\` can hold the module to them.

${shared}

export type LoadState = {
  /** The profile this session shows. Null when the config is missing, broken, or no profile fits. */
  profile: string | null
  /** The parsed config, or null. */
  config: Config | null
  /** One plain sentence per problem, ready to show. */
  problems: string[]
  /** What to do next, shown in the pane when there is nothing else to draw. */
  hint: string | null
}

declare module 'claude-code' {
  interface PluginState {
    'coordinator-band': {
      load: LoadState
      data: BandData | null
      answered: Record<string, string>
      collapsed: Record<string, boolean>
    }
  }
}
`
const target = new URL('../types/index.d.ts', import.meta.url)
if (process.argv.includes('--check')) {
  let current = ''
  try { current = readFileSync(target, 'utf8') } catch { /* missing */ }
  if (current !== text) { console.error('types/index.d.ts is out of date. Run: node scripts/gen-contract.mjs'); process.exit(1) }
} else {
  writeFileSync(target, text)
  console.log('wrote types/index.d.ts')
}
