// Embeds the recorded files in test/fixtures into test/fixtures.ts.
// Tests run in a sandbox with no file access, so they read the embedded copy.
// Run: node scripts/gen-fixtures.mjs        (rewrite)
//      node scripts/gen-fixtures.mjs --check (fail when the copy is out of date)
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'

const dir = new URL('../test/fixtures/', import.meta.url)
const target = new URL('../test/fixtures.ts', import.meta.url)
const names = readdirSync(dir).filter(n => !n.startsWith('.')).sort()
const body = names.map(n => `  ${JSON.stringify(n)}: ${JSON.stringify(readFileSync(new URL(n, dir), 'utf8'))},`).join('\n')
const text = `// Generated by scripts/gen-fixtures.mjs from test/fixtures. Do not edit.\nexport const FIXTURES: Record<string, string> = {\n${body}\n}\n`
if (process.argv.includes('--check')) {
  let current = ''
  try { current = readFileSync(target, 'utf8') } catch { /* missing */ }
  if (current !== text) { console.error('test/fixtures.ts is out of date. Run: node scripts/gen-fixtures.mjs'); process.exit(1) }
} else {
  writeFileSync(target, text)
  console.log(`wrote ${names.length} fixtures`)
}
